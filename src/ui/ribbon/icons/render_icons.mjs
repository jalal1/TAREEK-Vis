// Render the ribbon icons in svg/ to PNG files and write ribbon_icons.qrc.
//
// The app does not use the Qt SVG module, so the icons ship as PNG files at
// 16, 32 and 64 px. The SVG files are Lucide icons (ISC license), copied
// without change from the lucide-static package.
//
// To add an icon: copy <name>.svg from lucide-static/icons into svg/, then
// run this script from a folder where @resvg/resvg-js is installed:
//
//   npm install @resvg/resvg-js@2.6.2
//   node render_icons.mjs <path to src/ui/ribbon/icons>

import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { Resvg } from "@resvg/resvg-js";

const dir = process.argv[2];
if (!dir) {
    console.error("usage: node render_icons.mjs <icons folder>");
    process.exit(1);
}

const kColor = "#37474F";  // dark blue-gray: readable on the light ribbon
const kSizes = [16, 32, 64];

const svgDir = join(dir, "svg");
const pngDir = join(dir, "png");
mkdirSync(pngDir, { recursive: true });

const names = readdirSync(svgDir)
    .filter((f) => f.endsWith(".svg"))
    .map((f) => f.slice(0, -4))
    .sort();

const files = [];
for (const name of names) {
    const svg = readFileSync(join(svgDir, `${name}.svg`), "utf8")
        .replaceAll("currentColor", kColor);
    for (const size of kSizes) {
        const png = new Resvg(svg, { fitTo: { mode: "width", value: size } })
            .render().asPng();
        const file = `png/${name}-${size}.png`;
        writeFileSync(join(dir, file), png);
        files.push(file);
    }
}

const qrc = [
    "<!DOCTYPE RCC>",
    "<!-- Generated by render_icons.mjs. Do not edit. -->",
    "<RCC version=\"1.0\">",
    "    <qresource prefix=\"/ribbon\">",
    ...files.map((f) => `        <file alias="${f.slice(4)}">${f}</file>`),
    "    </qresource>",
    "</RCC>",
    "",
].join("\n");
writeFileSync(join(dir, "ribbon_icons.qrc"), qrc);

console.log(`${names.length} icons, ${files.length} files`);
